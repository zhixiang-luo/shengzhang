export function normalizeCategoryIcon(value: string | null | undefined): CategoryIconName {
  return value && CATEGORY_ICON_SET.has(value) ? (value as CategoryIconName) : 'other';
}

export function resolveCategoryIcon({
  explicitIcon,
  parentIcon,
}: {
  explicitIcon?: string | null;
  parentIcon?: string | null;
}): CategoryIconName {
  return normalizeCategoryIcon(explicitIcon ?? parentIcon);
}
